/**
 * Анимация перехода между страницами.
 *
 * Файл template.tsx отличается от layout одной важной деталью: React
 * пересоздаёт его при каждой навигации. Именно это и нужно — CSS-анимация
 * запускается заново, потому что элемент каждый раз новый. Layout в такой
 * ситуации бесполезен: он живёт между переходами и анимацию не перезапустит.
 *
 * Содержимое страницы слегка проявляется и поднимается снизу. Длительность
 * небольшая намеренно: переход случается часто, и долгая анимация начинает
 * раздражать уже на третьем клике.
 *
 * При системной настройке «уменьшить движение» анимация схлопывается
 * правилом в globals.css, а содержимое остаётся видимым.
 */
export default function Template({ children }: { children: React.ReactNode }) {
  return <div className="animate-page-in">{children}</div>;
}
