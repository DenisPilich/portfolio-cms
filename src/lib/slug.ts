/**
 * Преобразование заголовка в slug для адреса страницы.
 *
 * Кириллица транслитерируется: без этого «Как работает кэш» превратилось бы
 * в пустую строку, потому что в URL допустимы далеко не все символы.
 */
const TRANSLIT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh",
  з: "z", и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o",
  п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "ts",
  ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu",
  я: "ya",
};

export function slugify(value: string): string {
  return value
    .toLowerCase()
    // Точки убираем, а не заменяем дефисом: «Next.js» должно стать «nextjs»,
    // иначе получится «next-js» и тег разойдётся с уже существующим.
    .replace(/\./g, "")
    .split("")
    .map((char) => TRANSLIT[char] ?? char)
    .join("")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}
